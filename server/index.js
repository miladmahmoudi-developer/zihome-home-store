import express from "express";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import multer from "multer";

/**
 * Local development API for products and product-image uploads.
 * Product records live in a JSON file; uploaded images live in public/products.
 */
const app = express();
const PORT = 3001;

const dataFile = fileURLToPath(
    new URL("./data/products.json", import.meta.url),
);

const uploadDirectory = fileURLToPath(
    new URL("../public/products/", import.meta.url),
);

await mkdir(uploadDirectory, { recursive: true });

// These MIME types are the only image formats accepted by the upload route.
const imageExtensions = {
    "image/jpeg": ".jpg",
    "image/png": ".png",
    "image/webp": ".webp",
};

const upload = multer({
    // Give each image a unique filename to avoid overwriting another product image.
    storage: multer.diskStorage({
        destination: uploadDirectory,
        filename: (request, file, callback) => {
            callback(null, `${randomUUID()}${imageExtensions[file.mimetype]}`);
        },
    }),
    limits: {
        fileSize: 5 * 1024 * 1024,
        files: 1,
    },
    fileFilter: (request, file, callback) => {
        if (!imageExtensions[file.mimetype]) {
            return callback(new Error("Only JPG, PNG, and WebP images are allowed."));
        }

        callback(null, true);
    },
});

function handleImageUpload(request, response, next) {
    upload.single("image")(request, response, (error) => {
        if (error) {
            return response.status(400).json({ message: error.message });
        }

        next();
    });
}

app.use(express.json());

// Validate writes on the server even though the admin form validates them too.
const productSchema = z.object({
    name: z.string().trim().min(2),
    category: z.string().trim().min(2),
    price: z.coerce.number().positive(),
    image: z.string().trim().min(1),
    description: z.string().trim().min(5),
    stockCount: z.coerce.number().int().min(0),
    isFeatured: z.boolean(),
});

function validateProduct(request, response, next) {
    const result = productSchema.safeParse(request.body);

    if (!result.success) {
        return response.status(400).json({
            message: "Invalid product data",
            errors: result.error.issues.map((issue) => ({
                field: issue.path.join("."),
                message: issue.message,
            })),
        });
    }

    request.validatedProduct = result.data;
    next();
}

// Read and write the small local catalog as a { products: [...] } JSON object.
async function readProducts() {
    const fileContent = await readFile(dataFile, "utf8");
    return JSON.parse(fileContent).products;
}

async function saveProducts(products) {
    const fileContent = JSON.stringify({ products }, null, 2);
    await writeFile(dataFile, fileContent, "utf8");
}

app.get("/api/products", async (request, response) => {
    // The shop and admin list both use this endpoint.
    const products = await readProducts();
    response.json(products);
});

app.post("/api/products", validateProduct, async (request, response) => {
    const products = await readProducts();

    const newProduct = {
        // IDs and initial rating fields are generated by the server, not the form.
        ...request.validatedProduct,
        id: randomUUID(),
        rating: 0,
        reviewsCount: 0,
        inStock: request.validatedProduct.stockCount > 0,
    };

    products.push(newProduct);
    await saveProducts(products);

    response.status(201).json(newProduct);
});


app.get("/api/products/:id", async (request, response) => {
    const products = await readProducts();

    const product = products.find(
        (item) => String(item.id) === request.params.id,
    );

    if (!product) {
        return response.status(404).json({ message: "Product not found" });
    }

    response.json(product);
});

app.patch(
    "/api/products/:id",
    validateProduct,
    async (request, response) => {
        // The edit form sends the complete validated product, then the server keeps its ID.
        const products = await readProducts();

        const productIndex = products.findIndex(
            (item) => String(item.id) === request.params.id,
        );

        if (productIndex === -1) {
            return response.status(404).json({ message: "Product not found" });
        }

        const updatedProduct = {
            ...products[productIndex],
            ...request.validatedProduct,
            inStock: request.validatedProduct.stockCount > 0,
            id: products[productIndex].id,
        };

        products[productIndex] = updatedProduct;
        await saveProducts(products);

        response.json(updatedProduct);
    },
);


app.delete("/api/products/:id", async (request, response) => {
    const products = await readProducts();

    const productIndex = products.findIndex(
        (item) => String(item.id) === request.params.id,
    );

    if (productIndex === -1) {
        return response.status(404).json({ message: "Product not found" });
    }

    const [deletedProduct] = products.splice(productIndex, 1);
    await saveProducts(products);

    response.json(deletedProduct);
});

app.post("/api/uploads", handleImageUpload, (request, response) => {
    // Multer writes the file first; this response gives the client its public URL.
    if (!request.file) {
        return response.status(400).json({ message: "No image was uploaded." });
    }

    response.status(201).json({
        image: `/products/${request.file.filename}`,
    });
});



app.listen(PORT, () => {
    console.log(`Local API is running at http://localhost:${PORT}`);
});
